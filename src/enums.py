    RED = (0x00, 0x00, 0xFF, 0xFF)
    GREEN = (0x00, 0xFF, 0x00, 0xFF)
    BLUE = (0xFF, 0x00, 0x00, 0xFF)
    YELLOW = (0x00, 0xFF, 0xFF, 0xFF)
    MAGENTA = (0xFF, 0x00, 0xFF, 0xFF)
